import { chromium } from '/Users/chris/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
const browser = await chromium.launch();
for (const width of [320,393,1200]) {
  const page = await browser.newPage({viewport:{width,height:852}});
  await page.goto('http://127.0.0.1:5173/#/pages/group-apply/index?id=guide-02');
  await page.locator('.apply-note').waitFor();
  const fits = await page.locator('.apply-note').evaluate(el => { const r=el.getBoundingClientRect(); const p=el.parentElement.getBoundingClientRect(); return r.x>=p.x && r.right<=p.right+1; });
  assert.ok(fits,`apply textarea containment ${width}`);
  await page.screenshot({path:`local-tests/flows-20261014/apply-fixed-${width}.png`});
  await page.goto('http://127.0.0.1:5173/#/pages/group-members/index?id=my-game');
  await page.getByText('发起聊天',{exact:true}).click();
  const memberFits = await page.locator('.member-invite-input').evaluate(el => { const r=el.getBoundingClientRect(); const p=el.parentElement.getBoundingClientRect(); return r.x>=p.x && r.right<=p.right+1; });
  assert.ok(memberFits,`member textarea containment ${width}`);
  await page.screenshot({path:`local-tests/flows-20261014/member-sheet-fixed-${width}.png`});
  await page.close();
}
