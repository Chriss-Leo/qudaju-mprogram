import { chromium } from '/Users/chris/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
const browser = await chromium.launch();
const errors=[];
for(const width of [320,393,1200]) {
  const page=await browser.newPage({viewport:{width,height:852}});
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:5173/#/pages/messages/index');
  await page.locator('.message-action').first().waitFor();
  const card=page.locator('.invitation-row').last();
  const [action,heading,note,avatar,name]=await Promise.all(['.message-action','.message-heading','.message-note','.flow-avatar','.message-name'].map(selector=>card.locator(selector).boundingBox()));
  assert.ok(name.x>=avatar.x+avatar.width && Math.abs(name.x-heading.x)<1,'two titles align beside avatar');
  assert.ok(heading.y>=name.y+name.height && heading.y+heading.height<=avatar.y+avatar.height+2,'invite heading directly below name within avatar band');
  assert.ok(note.y>avatar.y+avatar.height,'gray information is a separate lower row');
  assert.ok(action.y>=heading.y+heading.height && action.width<152*width/750,'compact action beside lower information');
  assert.equal(await page.locator('.message-explanation .ui-icon').count(),1);
  await page.screenshot({path:`local-tests/flows-20261014/messages-polished-${width}.png`});
  await page.goto('http://127.0.0.1:5173/#/pages/chat/index?id=invite-active');
  await page.locator('.chat-input').waitFor();
  await page.locator('.chat-input input').fill('确认聊天框与按钮比例');
  const [input,send,composer]=await Promise.all(['.chat-input','.chat-send','.chat-composer'].map(selector=>page.locator(selector).boundingBox()));
  assert.ok(Math.abs(input.height-send.height)<1,'chat controls same height');
  assert.ok(send.width/composer.width>.19 && send.width/composer.width<.25,'send button should occupy approximately one fifth');
  await page.screenshot({path:`local-tests/flows-20261014/chat-polished-${width}.png`});
  await page.goto('http://127.0.0.1:5173/#/pages/chat/index?id=invite-history');
  await page.locator('.chat-closed').waitFor();
  const notice=await page.locator('.chat-closed').boundingBox();
  const footer=await page.locator('.flow-shell__footer').boundingBox();
  const computed=await page.locator('.chat-closed').evaluate(el=>({justify:getComputedStyle(el).justifyContent,text:getComputedStyle(el).textAlign}));
  assert.equal(computed.justify,'center'); assert.equal(computed.text,'center');
  assert.ok(Math.abs(notice.x+notice.width/2-footer.x-footer.width/2)<1,'notice centered within full footer');
  assert.ok(notice.width/footer.width>.85,'notice uses footer inner width');
  assert.equal(await page.locator('.chat-closed .ui-icon').count(),1);
  assert.equal(await page.locator('.chat-input').count(),0);
  await page.waitForFunction(()=>[...document.images].every(i=>i.complete));
  await page.screenshot({path:`local-tests/flows-20261014/history-polished-${width}.png`});
  await page.close();
}
