import { chromium } from '/Users/chris/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ headless: true });
const errors = [];
for (const width of [393, 320]) {
  const page = await browser.newPage({ viewport: { width, height: 852 }, deviceScaleFactor: 2 });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:5173/#/pages/service-detail/index?id=game-01');
  await page.locator('.detail-title').waitFor();
  await page.waitForFunction(() => [...document.images].every(image => image.complete));
  const title = await page.locator('.detail-title').evaluate(el => ({ whiteSpace: getComputedStyle(el).whiteSpace, width: el.clientWidth, content: el.scrollWidth }));
  assert.equal(title.whiteSpace, 'nowrap');
  assert.ok(title.content <= title.width, `sample title clipped at ${width}`);
  assert.equal(await page.locator('.detail-host__avatar').count(), 1);
  assert.equal(await page.locator('.detail-fact__symbol').count(), 0);
  const columns = await page.locator('.detail-facts > *').evaluateAll(els => els.map(el => el.getBoundingClientRect().width));
  assert.ok(Math.max(...columns) - Math.min(...columns) < 1);
  assert.equal(await page.locator('.detail-enrolled .avatar-stack__portrait').count(), 4);
  const header = await page.locator('.surface-header').boundingBox();
  const footer = await page.locator('.detail-actions').boundingBox();
  await page.screenshot({ path: `local-tests/detail-refresh-20261014/runtime-detail-${width}.png` });
  await page.locator('.detail-scroll .uni-scroll-view').last().evaluate(el => { el.scrollTop = el.scrollHeight; });
  const afterHeader = await page.locator('.surface-header').boundingBox();
  const afterFooter = await page.locator('.detail-actions').boundingBox();
  assert.equal(header.y, afterHeader.y);
  assert.equal(footer.y, afterFooter.y);
  await page.screenshot({ path: `local-tests/detail-refresh-20261014/runtime-detail-bottom-${width}.png` });
  await page.goto('http://127.0.0.1:5173/#/pages/groups/index');
  await page.locator('.group-card').first().waitFor();
  await page.waitForFunction(() => [...document.images].every(image => image.complete));
  const cards = page.locator('.group-card');
  assert.equal(await cards.first().locator('.group-card__apply').innerText(), '去报名');
  assert.equal(await cards.nth(2).locator('.group-card__apply--joined').innerText(), '已报名');
  assert.equal(await cards.nth(2).locator('.group-card__apply').getAttribute('disabled'), 'true');
  assert.equal(await page.locator('.group-card__corner').count(), 0);
  const fee = await cards.first().locator('.group-card__fee').boundingBox();
  const cardHeader = await cards.first().locator('.group-card__header').boundingBox();
  const action = await cards.first().locator('.group-card__apply').boundingBox();
  const bottom = await cards.first().locator('.group-card__footer').boundingBox();
  assert.ok(Math.abs(fee.x + fee.width - cardHeader.x - cardHeader.width) < 1);
  assert.ok(Math.abs(action.x + action.width - bottom.x - bottom.width) < 1);
  assert.ok(action.y > fee.y);
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  assert.equal(overflow, false);
  for (const [index, count] of [[0, 3], [1, 2], [2, 1]]) {
    assert.equal(await cards.nth(index).locator('.photo-grid__item').count(), count);
    const sizes = await cards.nth(index).locator('.photo-grid__item').evaluateAll(els => els.map(el => ({ width: el.getBoundingClientRect().width, height: el.getBoundingClientRect().height })));
    assert.ok(sizes.every(item => item.width > 0 && item.height > 0));
    if (count > 1) assert.ok(Math.max(...sizes.map(item => item.width)) - Math.min(...sizes.map(item => item.width)) < 1);
  }
  assert.equal(await cards.nth(2).locator('.avatar-stack__more').innerText(), '+1');
  await page.screenshot({ path: `local-tests/detail-refresh-20261014/runtime-list-${width}.png` });
  await page.close();
}
