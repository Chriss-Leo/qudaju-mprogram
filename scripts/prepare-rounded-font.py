"""Subset Resource Han Rounded CN Bold for the homepage headline.

Usage: python3 scripts/prepare-rounded-font.py /path/to/ResourceHanRoundedCN-Bold.ttf
Source: https://github.com/CyanoHao/Resource-Han-Rounded/releases/tag/v0.990
License: SIL OFL 1.1; see src/static/entry/fonts/RESOURCE-HAN-OFL.txt.
"""
import base64
import sys
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools import subset

chars = "今天，找点些好玩的搭子"
font = TTFont(sys.argv[1])
missing = set(chars) - {chr(cp) for cp in font.getBestCmap()}
assert not missing, missing
selection = subset.Subsetter(options=subset.Options())
selection.populate(text=chars)
selection.subset(font)
font.flavor = "woff2"
target = Path("src/static/entry/fonts/qudaju-rounded-bold.woff2")
font.save(target)
encoded = base64.b64encode(target.read_bytes()).decode()
Path("src/assets/rounded-font.ts").write_text(
    '// Resource Han Rounded CN Bold subset (SIL OFL 1.1). Generated by scripts/prepare-rounded-font.py.\n'
    + 'export const roundedFontSource = "url(\'data:font/woff2;base64,' + encoded + '\')";\n'
)
print(f"Headline font: {target.stat().st_size} bytes")
