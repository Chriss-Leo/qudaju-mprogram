"""Merge and subset only the approved display lettering, not the full CJK font."""
import base64
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.merge import Merger
from fontTools import subset
chars = set("趣搭局今天，找点些好玩的搭子")
files = []
for source in Path("node_modules/@fontsource/zcool-kuaile/files").glob("*.woff2"):
    font = TTFont(source)
    if set(font.getBestCmap()).intersection(map(ord, chars)):
        font.flavor = None
        options = subset.Options()
        selection = subset.Subsetter(options=options)
        selection.populate(text="".join(chars))
        selection.subset(font)
        target = Path("/private/tmp") / ("qudaju-" + source.stem + ".ttf")
        font.save(target)
        files.append(str(target))
font = Merger().merge(files)
font.flavor = "woff2"
target = Path("src/static/entry/fonts/qudaju-play.woff2")
font.save(target)
missing = chars - {chr(cp) for cp in font.getBestCmap()}
assert not missing, missing
encoded = base64.b64encode(target.read_bytes()).decode()
Path("src/assets").mkdir(exist_ok=True)
Path("src/assets/entry-font.ts").write_text(
    '// Subset of ZCOOL KuaiLe (OFL-1.1). Source generated by scripts/prepare-entry-font.py.\n'
    + 'export const entryFontSource = "url(\'data:font/woff2;base64,' + encoded + '\')";\n'
)
