CREATE TABLE IF NOT EXISTS public.auth_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 wechat_app_id VARCHAR(64) NOT NULL,
 wechat_open_id VARCHAR(128) NOT NULL,
 nickname VARCHAR(64) NOT NULL DEFAULT '微信用户',
 avatar_url TEXT NOT NULL DEFAULT '',
 phone_number VARCHAR(16),
 phone_verified_time TIMESTAMPTZ,
 status SMALLINT NOT NULL DEFAULT 1 CHECK (status IN (0,1)),
 create_user_id BIGINT NOT NULL DEFAULT 0,
 update_user_id BIGINT NOT NULL DEFAULT 0,
 create_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 update_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 deleted_at TIMESTAMPTZ,
 CONSTRAINT uk_auth_user_wechat UNIQUE (wechat_app_id,wechat_open_id)
);
CREATE INDEX IF NOT EXISTS idx_auth_user_deleted_at ON public.auth_user(deleted_at);
COMMENT ON TABLE public.auth_user IS '微信登录用户；初次注册审计主体0为系统';
CREATE TABLE IF NOT EXISTS public.base_language (
 code VARCHAR(64) PRIMARY KEY,
 type SMALLINT NOT NULL DEFAULT 1,
 en TEXT NOT NULL,
 zh TEXT NOT NULL,
 create_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 update_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
